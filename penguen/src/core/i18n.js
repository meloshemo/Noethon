const FALLBACK = 'tr';
let current = FALLBACK;
const listeners = new Set();

/** The language the browser is asking for, if the game speaks it. */
export function detectLang() {
  const wanted = typeof navigator === 'undefined' ? [] : navigator.languages ?? [navigator.language];
  for (const tag of wanted) {
    const id = String(tag ?? '').slice(0, 2).toLowerCase();
    if (STRINGS[id]) return id;
  }
  // Anywhere the game does not speak the local language, English travels
  // further than Turkish does.
  return 'en';
}

export function getLang() {
  return current;
}

export function isLang(id) {
  return Object.prototype.hasOwnProperty.call(STRINGS, id);
}

/**
 * Switch language and repaint every marked element.
 *
 * Returns true when the language actually changed, so callers can skip the
 * work of rebuilding their own screens when it did not.
 */
export function setLang(id, root) {
  const next = isLang(id) ? id : detectLang();
  const changed = next !== current;
  current = next;
  if (typeof document !== 'undefined') {
    document.documentElement.lang = next;
    document.documentElement.dataset.lang = next;
    applyI18n(root);
  }
  if (changed) for (const fn of listeners) fn(next);
  return changed;
}

/** Called after every language change, for screens that build themselves. */
export function onLang(fn) {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

/**
 * One string.
 *
 * `vars` fills `{name}` style slots. A key with no entry in either language
 * comes back as the key itself, which is ugly on purpose: it shows up in the
 * key-parity test long before it shows up on somebody's screen.
 */
export function t(key, vars) {
  let s = STRINGS[current]?.[key] ?? STRINGS[FALLBACK]?.[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  }
  return s;
}

/**
 * The right field of a piece of game data.
 *
 * Level names, penguin names, upgrade blurbs and so on live next to the thing
 * they describe rather than in the table above, because a skin whose name is
 * three files away from its drawing is a skin somebody will forget to rename.
 * English lives in an `en` object on the same entry.
 */
export function loc(entry, field = 'name') {
  if (!entry) return '';
  if (current !== FALLBACK) {
    const alt = entry[current]?.[field];
    if (typeof alt === 'string' && alt) return alt;
  }
  return entry[field] ?? '';
}

/** Repaint every marked element under `root`. */
export function applyI18n(root) {
  const scope = root ?? (typeof document === 'undefined' ? null : document);
  if (!scope) return;
  for (const el of scope.querySelectorAll('[data-i18n]')) {
    el.textContent = t(el.dataset.i18n);
  }
  for (const el of scope.querySelectorAll('[data-i18n-html]')) {
    el.innerHTML = t(el.dataset.i18nHtml);
  }
  for (const el of scope.querySelectorAll('[data-i18n-aria]')) {
    el.setAttribute('aria-label', t(el.dataset.i18nAria));
  }
  for (const el of scope.querySelectorAll('[data-i18n-title]')) {
    el.setAttribute('title', t(el.dataset.i18nTitle));
  }
  for (const el of scope.querySelectorAll('[data-i18n-ph]')) {
    el.setAttribute('placeholder', t(el.dataset.i18nPh));
  }
  if (scope === document) {
    const title = document.querySelector('title');
    if (title) title.textContent = `Pengu: ${t('title.tagline')}`;
  }
}

