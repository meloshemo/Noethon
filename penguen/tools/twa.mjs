/**
 * The Android package, generated rather than hand-kept.
 *
 *   node tools/twa.mjs            # android/ içine projeyi üret
 *   node tools/twa.mjs --check    # sadece ayar dosyasını doğrula
 *
 * Play's copy of this game is a **TWA**: a thin Android shell that opens the
 * published address full-screen, with no browser chrome, once the site proves
 * it is the same owner (see `docs/MAGAZA.md` §6). There is no second codebase
 * and there must never be one — the thing on Play is the thing on the web.
 *
 * Bubblewrap is the usual way to make one, and its CLI is interactive: it asks
 * about the JDK, the SDK, the colours, the signing key. That is fine for a
 * person doing it once and useless in a build that has to be repeatable. So
 * the settings live in `android/twa-manifest.json`, read here, and the project
 * is generated by calling Bubblewrap's own generator directly — the same code
 * path its `init` uses, minus the questions.
 *
 * Nothing generated by this is committed: `android/` is rebuilt from the
 * settings file on every run, in CI, and the only thing worth keeping is the
 * settings themselves.
 */

import { readFile, rm, mkdir } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dir = resolve(root, 'android');
const settings = resolve(dir, 'twa-manifest.json');

/**
 * What must be true of the settings, checked before anything is downloaded.
 *
 * Bubblewrap validates its own manifest, but only once it already has a JDK,
 * an SDK and a network. These four are the ones that are *ours* to get wrong,
 * and finding out about them after a two minute toolchain download in CI is
 * the kind of feedback loop that makes people stop running builds.
 */
function auditable(json) {
  const problems = [];
  if (!/^[a-z][a-z0-9_]*(\.[a-z][a-z0-9_]*)+$/.test(json.packageId ?? '')) {
    problems.push(`packageId Android kurallarına uymuyor: ${json.packageId}`);
  }
  if (!json.startUrl?.startsWith('/')) problems.push(`startUrl köke göre olmalı: ${json.startUrl}`);
  if (!json.host) problems.push('host boş');
  if (!Number.isInteger(json.appVersionCode) || json.appVersionCode < 1) {
    problems.push(`appVersionCode tamsayı olmalı: ${json.appVersionCode}`);
  }
  // Play counts this one and refuses an upload that repeats it, so the mistake
  // is worth catching before the upload rather than after.
  if (!/^\d+\.\d+\.\d+$/.test(json.appVersionName ?? '')) {
    problems.push(`appVersionName x.y.z olmalı: ${json.appVersionName}`);
  }
  return problems;
}

const json = JSON.parse(await readFile(settings, 'utf8'));
const problems = auditable(json);
for (const p of problems) console.log(`  ✗ ${p}`);
if (problems.length) {
  console.log(`\n✗ ${problems.length} sorun — android/twa-manifest.json`);
  process.exit(1);
}
console.log(`  ✓ ayarlar geçerli — ${json.packageId} ${json.appVersionName} (${json.appVersionCode})`);
console.log(`  ✓ açılış adresi — https://${json.host}${json.startUrl}`);

if (process.argv.includes('--check')) {
  console.log('\n✓ TWA ayarları sağlam.');
  process.exit(0);
}

/*
 * Bubblewrap is a build dependency and is installed by the workflow rather
 * than carried in `package.json`: it pulls in nearly three hundred packages,
 * and a repository whose whole point is that it has no dependencies should
 * not grow them for a thing that runs on a server twice a year.
 */
let core;
try {
  core = (await import('@bubblewrap/core')).default;
} catch {
  console.log('\n@bubblewrap/core kurulu değil. Kurmak için:');
  console.log('  npm install --no-save @bubblewrap/core');
  process.exit(1);
}

const { TwaManifest, TwaGenerator, ConsoleLog } = core;

// Regenerated from scratch every time: a half-updated Android project is a
// thing nobody can read, and everything in here is derived anyway.
await rm(resolve(dir, 'app'), { recursive: true, force: true });
await mkdir(dir, { recursive: true });

const manifest = await TwaManifest.fromFile(settings);
const invalid = manifest.validate();
if (invalid) {
  console.log(`\n✗ Bubblewrap ayarları reddetti: ${invalid}`);
  process.exit(1);
}

console.log('\nAndroid projesi üretiliyor...');
await new TwaGenerator().createTwaProject(dir, manifest, new ConsoleLog('twa'));
console.log('\n✓ android/ hazır — gradle ile paketlenebilir.');
